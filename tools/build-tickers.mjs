// Builds public/tickers.js, the long tail of the ticker picker, from Nasdaq's
// public screener download (every US-listed stock, with names and market caps).
//
//   curl -A "Mozilla/5.0" "https://api.nasdaq.com/api/screener/stocks?tableonly=true&limit=25&offset=0&download=true" -o /tmp/screener.json
//   node tools/build-tickers.mjs /tmp/screener.json
//
// The hand-written list in app.js stays first, with its short names; this file
// only adds what that list lacks. Kept out of app.js because 4,000 names do
// not belong in the file that draws the chart.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-tickers.mjs screener.json'); process.exit(1); }
const rows = JSON.parse(fs.readFileSync(src, 'utf8')).data.rows;

const MIN_CAP = Number(process.env.MIN_CAP || 100e6);   // below this it is mostly shells and SPACs

// Not a company's common stock: warrants, units, rights, preferreds, notes,
// closed-end funds, blank-check vehicles. Anyone who wants these can still
// type the symbol; they just are not offered.
const SKIP = /\b(warrants?|units?|rights?|preferred|preference|notes?|debentures?|bonds?|ETF|ETN|fund|investors trust|income trust|term trust|shares? of beneficial (interest|ownership)|acquisition|SPAC|(income|utility|equity|dividend|opportunit\w*|strateg\w*|municipal|global|total return|premium|tax|senior|floating|convertible|high yield|allocation|multi-asset|real assets|term) (\w+ )?trust|depositary shares?,? each representing .*preferred)\b/i;

// Nasdaq writes "Aveanna Healthcare Holdings Inc. Common Stock"; the picker
// wants "Aveanna Healthcare Holdings".
function cleanName(raw) {
  let n = raw.replace(/\s+/g, ' ').trim();
  const cls = n.match(/\bClass ([A-Z])\b/);
  // Everything from the share-class or share-type words onward is boilerplate.
  n = n.replace(/\s*[-–]?\s*\bClass [A-Z]\b.*$/, '');
  n = n.replace(/\s*\b(American Depositary Shares?|American Depository Shares?|Depositary Shares?|Depository Shares?|Ordinary Shares?|Common Shares?|Common Stock|Capital Stock|Subordinate Voting Shares?|Limited Voting Shares?|Voting Shares?|Voting|(New York|NY) Registry Shares?|Registry Shares?|Shares?|Stock|Common)\b.*$/i, '');
  n = n.replace(/\s*\(?\beach\b.*$/i, '').replace(/\s*\brepresenting\b.*$/i, '');
  n = n.replace(/\s*\((The|New)\)/gi, '').replace(/\s+\bNEW\b$/i, '').replace(/\s+\bNew\b$/, '');
  n = n.replace(/[,\s]+$/, '');
  // corporate suffixes, possibly several ("Holdings Inc.", "Group plc")
  for (let i = 0; i < 3; i++) {
    n = n.replace(/[,\s]+(Inc\.?|Incorporated|Corp\.?|Corporation|Co\.?|Company|Ltd\.?|Limited|LLC|L\.?P\.?|plc|PLC|N\.?V\.?|S\.?A\.?|A\.?G\.?|SE|S\.?p\.?A\.?|AB|ASA|Oyj|Bhd)\.?$/i, '').trim();
    n = n.replace(/\s+(and|&)$/i, '').trim();
  }
  n = n.replace(/[,\s.]+$/, '').trim();
  if (cls && !/\(Class [A-Z]\)$/.test(n)) n += ` (Class ${cls[1]})`;
  return n;
}

const out = [];
const seen = new Set();
for (const r of rows) {
  const cap = Number(r.marketCap || 0);
  if (!(cap >= MIN_CAP)) continue;
  if (SKIP.test(r.name)) continue;
  // Twelve Data writes share classes with a dot: BRK/B is BRK.B
  const sym = String(r.symbol).trim().replace(/\//g, '.').replace(/\^.*$/, '');
  if (!/^[A-Z]{1,5}(\.[A-Z])?$/.test(sym)) continue;
  if (seen.has(sym)) continue;
  const name = cleanName(r.name);
  if (!name) continue;
  seen.add(sym);
  out.push({ sym, name, cap });
}
// Biggest first: the picker shows the first eight matches, and "A" should
// surface Apple-sized companies before shells.
out.sort((a, b) => b.cap - a.cap);

const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.join(here, '..', 'public', 'tickers.js');
const body = out.map(t => JSON.stringify([t.sym, t.name])).join(',\n');
fs.writeFileSync(dest,
`// Generated by tools/build-tickers.mjs from Nasdaq's screener download on ${new Date().toISOString().slice(0, 10)}.
// US-listed common stocks with a market cap of at least $${Math.round(MIN_CAP / 1e6)}M, biggest first.
// app.js merges this behind its own short list. Do not edit by hand; rerun the tool.
window.TICKER_LIST = [
${body}
];
`);
console.log(`${out.length} tickers -> ${path.relative(process.cwd(), dest)} (${(fs.statSync(dest).size / 1024).toFixed(0)} KB)`);
