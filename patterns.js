// Bar-level patterns at bar i. Needs at least 140 bars before i.
function barPatterns(c, i) {
  if (i < 140 || i >= c.length) return [];
  const k = c[i], p = c[i - 1], q = c[i - 2];
  const body = k.close - k.open, rng = k.high - k.low;
  if (!(rng > 0) || !(p.close > 0)) return [];
  let s2 = 0; for (let j = i - 19; j <= i; j++) { const r = Math.log(c[j].close / c[j - 1].close); s2 += r * r; }
  const sd20 = Math.sqrt(s2 / 20) || 1e-9;
  let rs = 0; for (let j = i - 13; j <= i; j++) rs += c[j].high - c[j].low; const avgR = rs / 14;
  let vs = 0, vn = 0; for (let j = i - 50; j < i; j++) if (c[j].volume) { vs += c[j].volume; vn++; }
  const volRatio = vn && k.volume ? k.volume / (vs / vn) : 0;
  const ab = Math.abs(body), up = k.high - Math.max(k.open, k.close), lo = Math.min(k.open, k.close) - k.low;
  const pb = p.close - p.open, qb = q.close - q.open;
  const down5 = k.close < c[i - 5].close && p.close < c[i - 6].close;
  const up5 = k.close > c[i - 5].close && p.close > c[i - 6].close;
  const out = [];
  if (ab <= 0.1 * rng) out.push('doji');
  const smallBody = ab > 0.02 * rng;
  if (down5 && lo >= 2 * ab && up <= 0.25 * rng && smallBody) out.push('hammer');
  if (up5 && lo >= 2 * ab && up <= 0.25 * rng && smallBody) out.push('hanging man');
  if (up5 && up >= 2 * ab && lo <= 0.25 * rng && smallBody) out.push('shooting star');
  if (down5 && up >= 2 * ab && lo <= 0.25 * rng && smallBody) out.push('inverted hammer');
  if (down5 && pb < 0 && body > 0 && k.open <= p.close && k.close >= p.open && ab > Math.abs(pb)) out.push('bullish engulfing');
  if (up5 && pb > 0 && body < 0 && k.open >= p.close && k.close <= p.open && ab > Math.abs(pb)) out.push('bearish engulfing');
  if (down5 && pb < 0 && Math.abs(pb) > avgR * 0.6 && body > 0 && k.open > p.close && k.close < p.open) out.push('bullish harami');
  if (up5 && pb > 0 && Math.abs(pb) > avgR * 0.6 && body < 0 && k.open < p.close && k.close > p.open) out.push('bearish harami');
  if (down5 && pb < 0 && Math.abs(pb) > avgR * 0.6 && k.open < p.low && body > 0 && k.close > (p.open + p.close) / 2 && k.close < p.open) out.push('piercing line');
  if (up5 && pb > 0 && Math.abs(pb) > avgR * 0.6 && k.open > p.high && body < 0 && k.close < (p.open + p.close) / 2 && k.close > p.open) out.push('dark cloud cover');
  if (qb < 0 && Math.abs(qb) > avgR * 0.6 && Math.abs(pb) < Math.abs(qb) * 0.3 && Math.max(p.open, p.close) < q.close && body > 0 && k.close > (q.open + q.close) / 2 && q.close < c[i - 7].close) out.push('morning star');
  if (qb > 0 && Math.abs(qb) > avgR * 0.6 && Math.abs(pb) < Math.abs(qb) * 0.3 && Math.min(p.open, p.close) > q.close && body < 0 && k.close < (q.open + q.close) / 2 && q.close > c[i - 7].close) out.push('evening star');
  const white = x => x.close > x.open && (x.close - x.open) > 0.6 * (x.high - x.low);
  const black = x => x.close < x.open && (x.open - x.close) > 0.6 * (x.high - x.low);
  if (white(k) && white(p) && white(q) && k.close > p.close && p.close > q.close && k.open > p.open && k.open < p.close && p.open > q.open && p.open < q.close) out.push('three white soldiers');
  if (black(k) && black(p) && black(q) && k.close < p.close && p.close < q.close && k.open < p.open && k.open > p.close && p.open < q.open && p.open > q.close) out.push('three black crows');
  if (body > 0 && ab >= 0.9 * rng && rng > avgR) out.push('bullish marubozu');
  if (body < 0 && ab >= 0.9 * rng && rng > avgR) out.push('bearish marubozu');
  if (Math.abs(k.high - p.high) <= 0.002 * k.close && up5 && pb > 0 && body < 0) out.push('tweezer top');
  if (Math.abs(k.low - p.low) <= 0.002 * k.close && down5 && pb < 0 && body > 0) out.push('tweezer bottom');
  const g = Math.log(k.open / p.close) / sd20;
  if (g > 1) out.push(body >= 0 ? 'gap up, held' : 'gap up, faded');
  if (g < -1) out.push(body <= 0 ? 'gap down, held' : 'gap down, recovered');
  let nr7 = true; for (let j = 1; j < 7; j++) if (c[i - j].high - c[i - j].low <= rng) { nr7 = false; break; }
  if (nr7) out.push('NR7');
  if (k.high < p.high && k.low > p.low) out.push('inside day');
  if (k.high > p.high && k.low < p.low) out.push('outside day');
  let hh = -Infinity, ll = Infinity; for (let j = 1; j <= 20; j++) { hh = Math.max(hh, c[i - j].high); ll = Math.min(ll, c[i - j].low); }
  if (k.close > hh) out.push(volRatio > 1.5 ? '20-day breakout up, high volume' : '20-day breakout up');
  if (k.close < ll) out.push(volRatio > 1.5 ? '20-day breakdown, high volume' : '20-day breakdown');
  const bw = (e) => { let m = 0; for (let j = e - 19; j <= e; j++) m += c[j].close; m /= 20; let v = 0; for (let j = e - 19; j <= e; j++) v += (c[j].close - m) ** 2; return Math.sqrt(v / 20) / m; };
  const cur = bw(i); let squeeze = true; for (let e = i - 120; e < i; e += 2) if (bw(e) <= cur) { squeeze = false; break; }
  if (squeeze) out.push('Bollinger squeeze');
  const r = Math.log(k.close / p.close) / sd20;
  if (volRatio > 2) out.push(r > 0 ? 'volume spike, up day' : 'volume spike, down day');
  if (r < -2.5) out.push('big down day');
  if (r > 2.5) out.push('big up day');
  let lo60 = Infinity, hi60 = -Infinity; for (let j = i - 60; j < i - 5; j++) { lo60 = Math.min(lo60, c[j].low); hi60 = Math.max(hi60, c[j].high); }
  if (k.low <= lo60 * 1.01 && k.low >= lo60 * 0.99 && k.close > lo60 * 1.01) out.push('bounce off 60-day support');
  if (k.high >= hi60 * 0.99 && k.high <= hi60 * 1.01 && k.close < hi60 * 0.99) out.push('rejected at 60-day resistance');
  const step = k.close > 200 ? 100 : k.close > 20 ? 10 : null;
  if (step && Math.floor(k.close / step) > Math.floor(p.close / step)) out.push('crosses round number up');
  if (step && Math.floor(k.close / step) < Math.floor(p.close / step)) out.push('crosses round number down');
  return out;
}

// Classical patterns, causally: walk forward bar by bar; a swing high/low on
// closes is confirmed W bars after it; the alternating swing list is updated
// at confirmation time; each new swing opens 30-bar watches for a neckline
// (or triangle edge) break, cancelled if that swing is later superseded.
// Returns { barIndex: [names] } for the bars on which a pattern completed.
function classicalSignals(c) {
  const W = 5, sig = {}, A = [], watches = [];
  const near = (a, b, tol) => Math.abs(a - b) / ((a + b) / 2) <= tol;
  for (let t = 2 * W; t < c.length; t++) {
    const i = t - W; // candidate swing confirmed now
    let hi = true, lo = true;
    for (let j = 1; j <= W; j++) {
      if (c[i - j].close >= c[i].close || c[i + j].close > c[i].close) hi = false;
      if (c[i - j].close <= c[i].close || c[i + j].close < c[i].close) lo = false;
    }
    let changed = false;
    if (hi || lo) {
      const p = { i, v: c[i].close, t: hi ? 'H' : 'L' }, l = A[A.length - 1];
      if (l && l.t === p.t) { if ((p.t === 'H' && p.v > l.v) || (p.t === 'L' && p.v < l.v)) { A[A.length - 1] = p; changed = true; } }
      else { A.push(p); changed = true; }
    }
    if (changed) {
      const last = A[A.length - 1];
      // (a superseded swing cancels its watches: checked in the loop below)
      const n = A.length - 1, open = (test, name) => watches.push({ anchor: last, anchorIdx: n, until: t + 30, test, name });
      if (n >= 4) {
        const [a, b, d, e, f] = A.slice(n - 4, n + 1);
        if (f.i - a.i <= 120) {
          if (a.t === 'H' && d.v > a.v * 1.02 && d.v > f.v * 1.02 && near(a.v, f.v, 0.03)) { const neck = Math.min(b.v, e.v); open(x => x < neck ? 'head and shoulders' : null); }
          if (a.t === 'L' && d.v < a.v * 0.98 && d.v < f.v * 0.98 && near(a.v, f.v, 0.03)) { const neck = Math.max(b.v, e.v); open(x => x > neck ? 'inverse head and shoulders' : null); }
        }
      }
      if (n >= 2) {
        const [a, b, d] = A.slice(n - 2, n + 1);
        if (d.i - a.i <= 80 && d.i - a.i >= 10) {
          if (a.t === 'H' && near(a.v, d.v, 0.02) && b.v < a.v * 0.95) open(x => x < b.v ? 'double top' : null);
          if (a.t === 'L' && near(a.v, d.v, 0.02) && b.v > a.v * 1.05) open(x => x > b.v ? 'double bottom' : null);
        }
      }
      if (n >= 3) {
        const w4 = A.slice(n - 3, n + 1), H = w4.filter(p => p.t === 'H'), L = w4.filter(p => p.t === 'L');
        if (H.length === 2 && L.length === 2 && w4[3].i - w4[0].i <= 80) {
          const flatH = near(H[0].v, H[1].v, 0.015), flatL = near(L[0].v, L[1].v, 0.015);
          const lowerH = H[1].v < H[0].v * 0.985, higherL = L[1].v > L[0].v * 1.015;
          const kind = flatH && higherL ? 'ascending triangle' : flatL && lowerH ? 'descending triangle' : lowerH && higherL ? 'symmetric triangle' : null;
          if (kind) { const top = H[1].v, bot = L[1].v; open(x => x > top ? kind + ', breaks up' : x < bot ? kind + ', breaks down' : null); }
        }
      }
    }
    for (const w of watches) {
      if (w.dead || w.done || t > w.until) continue;
      if (A[w.anchorIdx] !== w.anchor) { w.dead = true; continue; }
      const nm = w.test(c[t].close);
      if (nm) { (sig[t] ||= []).push(nm); w.done = true; }
    }
    if (watches.length > 200) for (let k = watches.length - 1; k >= 0; k--) if (watches[k].dead || watches[k].done || t > watches[k].until) watches.splice(k, 1);
  }
  return sig;
}

// Stats generated by the backtest; loaded lazily so a missing file only
// hides the record, never the chart.
let STATS = null;
function stats() {
  if (STATS) return STATS;
  try { STATS = require('./pattern-stats.json'); } catch (e) { STATS = {}; }
  return STATS;
}

// What the site shows: patterns on the latest bar, and classical patterns that
// completed in the last five bars, each with its measured record.
function chartPatterns(candles, opts) {
  const crypto = !!(opts && opts.crypto);
  const n = candles.length;
  if (n < 160) return { items: [], crypto };
  const found = barPatterns(candles, n - 1).map(name => ({ name, daysAgo: 0 }));
  const cls = classicalSignals(candles);
  for (let i = Math.max(0, n - 5); i < n; i++) for (const name of (cls[i] || [])) found.push({ name, daysAgo: n - 1 - i });
  const S = stats()[crypto ? 'crypto' : 'stocks'] || {};
  const items = found.map(f => Object.assign({ about: NAMES[f.name] || '' }, f, { record: S[f.name] || null }));
  return { items, crypto };
}

module.exports = { barPatterns, classicalSignals, chartPatterns, NAMES };
