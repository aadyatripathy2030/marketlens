//
// What the measurement found (2016-2026 held out, 111 large US stocks, rules
// fixed on 2006-2015, ETFs left out): no pattern here predicted direction in the same way in
// both periods. Several did predict how big the next week's moves were. The
// stats table (pattern-stats.json) is generated by the backtest, never typed.

